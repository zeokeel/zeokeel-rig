func TestOutOfBoundsPathRefused(t *testing.T) {
	parent := t.TempDir()
	root := filepath.Join(parent, "workspace")
	if err := os.MkdirAll(root, 0o755); err != nil {
		t.Fatal(err)
	}
	registry := testRegistry(t, Options{Policy: newPolicy(t, root), Now: func() time.Time { return fixedNow }})

	content := invokeError(t, registry, `{"path":"../escape.md"}`)
	if !strings.Contains(content, "refused by the sandbox") {
		t.Fatalf("escape attempt = %q", content)
	}
	if _, err := os.Stat(filepath.Join(parent, "escape.md")); !errors.Is(err, os.ErrNotExist) {
		t.Fatalf("sandbox escape wrote a file: %v", err)
	}
	outside := filepath.Join(t.TempDir(), "outside.md")
	if content := invokeError(t, registry, `{"path":`+quote(outside)+`}`); !strings.Contains(content, "refused by the sandbox") {
		t.Fatalf("absolute outside path = %q", content)
	}
}

func TestPolicyRequired(t *testing.T) {
	if content := invokeError(t, testRegistry(t, Options{}), `{}`); !strings.Contains(content, "no sandbox policy") {
		t.Fatalf("nil policy = %q", content)
	}
	root := t.TempDir()
	readOnly := sandbox.New(sandbox.WithRoots(root), sandbox.WithReadOnly(true))
	if content := invokeError(t, testRegistry(t, Options{Policy: readOnly}), `{}`); !strings.Contains(content, "read-only") {
		t.Fatalf("read-only policy = %q", content)
	}
	if content := invokeError(t, testRegistry(t, Options{Policy: sandbox.New()}), `{}`); !strings.Contains(content, "no filesystem root") {
		t.Fatalf("rootless policy = %q", content)
	}
}

