var fixedNow = time.Date(2026, 11, 6, 12, 0, 0, 0, time.UTC)

func newPolicy(t *testing.T, root string) *sandbox.Policy {
	t.Helper()
	return sandbox.New(sandbox.WithRoots(root))
}

func testRegistry(t *testing.T, opts Options) *rigtools.Registry {
	t.Helper()
	return rigtools.NewRegistry(NewReportTool(opts))
}

func invoke(t *testing.T, registry *rigtools.Registry, arguments string) (v1.ToolResult, error) {
	t.Helper()
	return registry.Invoke(context.Background(), v1.ToolCall{ID: "call-1", Name: ToolName, Arguments: arguments})
}

func invokeOK(t *testing.T, registry *rigtools.Registry, arguments string) string {
	t.Helper()
	result, err := invoke(t, registry, arguments)
	if err != nil {
		t.Fatalf("report: %v", err)
	}
	if result.IsError {
		t.Fatalf("report returned an error result: %s", result.Content)
	}
	return result.Content
}

func invokeError(t *testing.T, registry *rigtools.Registry, arguments string) string {
	t.Helper()
	result, err := invoke(t, registry, arguments)
	if err != nil {
		t.Fatalf("report: %v", err)
	}
	if !result.IsError {
		t.Fatalf("report did not return an error result: %q", result.Content)
	}
	return result.Content
}

func populatedLog() *session.MemoryLog {
	log := session.NewMemoryLog()
	stamp := time.Date(2026, 11, 6, 12, 0, 0, 0, time.UTC)
	log.Append(v1.SessionEvent{SessionID: "s1", Type: "user_message", Time: stamp, Payload: json.RawMessage(`{"text":"hello"}`)})
	log.Append(v1.SessionEvent{SessionID: "s1", Type: "tool_call", Time: stamp, Payload: json.RawMessage(`{"tool":"read_file"}`)})
	log.Append(v1.SessionEvent{SessionID: "s1", Type: "tool_result", Payload: json.RawMessage(`{"ok":true}`)})
	log.Append(v1.SessionEvent{SessionID: "s1", Type: "error", Payload: json.RawMessage(`{"message":"boom"}`)})
	return log
}

func TestToolCatalog(t *testing.T) {
	tool := NewReportTool(Options{})
	if tool.Name() != ToolName {
		t.Fatalf("Name() = %q, want %q", tool.Name(), ToolName)
	}
	if strings.TrimSpace(tool.Description()) == "" {
		t.Fatal("report has an empty description")
	}
	schema := tool.Schema()
	if schema["type"] != "object" {
		t.Fatalf("schema type = %v", schema["type"])
	}
	properties, ok := schema["properties"].(map[string]any)
	if !ok {
		t.Fatal("schema has no properties")
	}
	for _, name := range []string{"path", "title", "session_id", "limit", "content"} {
		if _, ok := properties[name]; !ok {
			t.Fatalf("schema has no %q property", name)
		}
	}
	if required, _ := schema["required"].([]string); len(required) != 0 {
		t.Fatalf("required = %v, want none", required)
	}
}

func TestDefaultReportFile(t *testing.T) {
	root := t.TempDir()
	registry := testRegistry(t, Options{Log: populatedLog(), Policy: newPolicy(t, root), Now: func() time.Time { return fixedNow }})

	content := invokeOK(t, registry, `{"title":"Sprint report","session_id":"s1"}`)
	wantName := "rig-report-20261106-120000.md"
	if !strings.Contains(content, wantName) {
		t.Fatalf("report result = %q, want the default file name %q", content, wantName)
	}
	for _, want := range []string{"events: 4", "tool calls: 1", "errors: 1", "words:"} {
		if !strings.Contains(content, want) {
			t.Fatalf("report result = %q, want %q", content, want)
		}
	}
	path := filepath.Join(root, wantName)
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read report %q: %v", path, err)
	}
	body := string(data)
	for _, want := range []string{
		"# Sprint report",
		"Generated: 2026-11-06T12:00:00Z",
		"Scope: session s1",
		"Events: 4",
		"Tool calls: 1",
		"Errors: 1",
		"## Event types",
		"tool_call: 1",
		"## Recent events",
		"#2 tool_call",
		"Generated by the Rig `report` tool.",
	} {
		if !strings.Contains(body, want) {
			t.Fatalf("report body = %q, want %q", body, want)
		}
	}
	// The reported word count matches the written document.
	if !strings.Contains(content, "words: "+strconv.Itoa(len(strings.Fields(body)))) {
		t.Fatalf("report result = %q, want words: %d", content, len(strings.Fields(body)))
	}
}

func TestExplicitPathAndContent(t *testing.T) {
	root := t.TempDir()
	registry := testRegistry(t, Options{Log: populatedLog(), Policy: newPolicy(t, root), Now: func() time.Time { return fixedNow }})

	content := invokeOK(t, registry, `{"path":"reports/out.md","title":"Release","content":"## Extra\n\nnotes here"}`)
	path := filepath.Join(root, "reports", "out.md")
	if !strings.Contains(content, path) {
		t.Fatalf("report result = %q, want %q", content, path)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read report: %v", err)
	}
	body := string(data)
	if !strings.Contains(body, "# Release") || !strings.Contains(body, "## Content") || !strings.Contains(body, "notes here") {
		t.Fatalf("report body = %q", body)
	}
	// No session_id: scope is the searchable event set.
	if !strings.Contains(body, "Scope: searchable events") {
		t.Fatalf("report body = %q, want the searchable-events scope", body)
	}
}

