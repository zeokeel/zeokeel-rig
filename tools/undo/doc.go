// Package undo 提供"撤销上一回合文件改动"的能力与 undo 工具。
//
// 仓库里已经有两件相近但不同的事：tools/worktree 做的是整树隔离（换一个检出目录），
// checkpoint 做的是中断恢复（把整个会话状态落盘）。本包补上第三件：**把工作区回退到
// 某一回合开始时的样子**——回合里新建的文件删掉、改动的写回、删掉的写回，其余文件
// 一律不碰。
//
// # 工作方式
//
// 回合开始前调用 Take（或 Tracker.Begin）拍一份快照：递归遍历工作区，把每个普通文件
// 的路径、权限、大小、inode 身份与内容（在限额内）记在内存里；符号链接记录目标文本。之后用 Changes 对比当前状态与快照，
// 用 Revert 把差异抹平。
//
//   - 新增：当前有、快照没有 → 删除该文件（不删目录：目录里可能有别的东西）。
//   - 改动：路径都在、内容不同 → 写回快照里的字节，并恢复原权限。
//   - 删除：快照有、当前没有 → 把快照里的字节写回（必要时创建父目录）。
//
// 回退是**全有或全无**的：先把所有目标内容备好，再逐文件以"临时文件 + rename"落盘；
// 任何一个文件失败，已写的文件会按回退前的状态再改回去，然后返回错误。因此"回退到
// 一半"不会留在盘上。
//
// # 符号链接、硬链接与 TOCTOU
//
// 所有文件访问都经 internal/fsguard 的 traversal-safe 句柄（内部是 os.Root）：路径
// 逃逸（绝对路径、".."、父目录被换成指向根外的符号链接）由内核在系统调用时拦住，
// 因此"校验之后、落盘之前被换成符号链接"的 TOCTOU 不再是 undo 的缺口。
//
// 快照时还会记录工作区根的身份，且**四个入口（Changes/ChangesForPath/Revert/RevertPath）
// 一进来就先复核，早于任何"没有变更就返回"的提前返回**：
//
//   - 类型：根必须仍是真实目录（不是符号链接）；
//   - (dev, ino)：根不能换成别的目录（对 bind mount 这类场景敏感）；
//   - 根实例 cookie：写在根 inode 上的随机值（Linux 扩展属性 `user.rig-undo-root`）。
//     只比 (dev,ino) 有一个洞——目录被删掉后在**同一父目录**重建时，文件系统会把刚释放的
//     inode 分给新目录（ext4 实测几乎必然复用），(dev,ino) 完全一致；cookie 是新目录
//     不可能带着的，因此"读不到或值不一致"就判定根被替换。
//
// 任何一项不符都返回 ErrRootReplaced，绝不把快照内容倒进一个不同的工作区。cookie 不产生
// 目录项（工作区里看不到它）、不进快照、也不会被回退删除；非 Linux 平台或文件系统不支持
// xattr 时，Take 仍然成功，根身份校验退化为"类型 + (dev,ino)"。
//
// 符号链接是快照里的第一类条目：记录目标文本，**绝不读取目标内容**（指向根外的链接
// 也不会被读出字节）。回退时：
//
//   - 链接目标变了        → 删掉链接、按快照里的目标重建；
//   - 链接被换成普通文件  → 删掉文件、按住快照重建链接；
//   - 普通文件被换成链接  → 删掉链接、写回普通文件（**不写穿**到链接目标）；
//   - 链接被删除          → 按快照里的目标重建；
//   - 回合里新增的链接    → 删除链接本身（不触碰它的目标）。
//
// 恢复链接时按**快照里记录的目标文本原样重建**：绝对路径（`/tmp/x/target.txt`）与
// 上跳相对路径（`../../etc/passwd`）都照原样写回。目标可以在根外——链接本身仍然只在
// 根内，undo 不会顺着它读写任何内容；反过来，如果把"目标必须在根内"强加给恢复路径，
// 合法的绝对/共享链接就无法 undo（整次回退会因全有或全无而失败）。
//
// 硬链接：快照记录每个路径的 (dev, ino)。回退用 rename 落盘，会把被写的路径换成新
// inode，因此同一 inode 的其它路径会保留回合里的内容，硬链接关系也不会被重建。凡是
// 出现"同组路径没有被一起回退"的情况，结果里会带上 Change.HardlinkOf 并在文案里
// 输出一条 warning（`affected N`）——绝不静默。
//
// # 不回退不可信的东西
//
// 有些内容不适合进内存快照：二进制文件（含 NUL）、超过 Options.MaxFileBytes 的文件、
// 以及超出 Options.MaxTotalBytes 总预算的文件。它们仍被跟踪（大小/时间），但内容不
// 备份；对比时若发现被改动，会以 Change.Reason="not-backed-up: …" 报告，Revert 跳过
// 它们并在结果里汇总一条警告——**绝不静默**。默认忽略 .git、node_modules、vendor、
// dist、build（用户规则追加在这份默认之上），符号链接不跟踪、不跟随。
//
// # 工具
//
// undo 工具默认回退"最近一次 Begin 的快照"：
//
//	undo {}                       // 回退最近一回合
//	undo {"turn": 2}              // 回退到第 2 回合开始时的状态
//	undo {"dry_run": true}        // 只报告将要发生的变更，不落盘
//	undo {"path": "src/a.go"}     // 只回退这一个文件（相对工作区根，越界报错）
//
// 回合号由 Tracker 分配：Begin 返回递增的回合号并按 Options.Retain（默认 10）保留最近
// 若干份快照，更老的被丢弃；turn<=0 表示最近一次。Tracker 并发安全（内部加锁；
// Begin 的文件遍历不在锁内，因此多个会话可以并行拍快照）。
//
// # 组装
//
//	tracker := undo.NewTracker(workspaceRoot, undo.Options{})
//	tools := []rig.Tool{undo.New(tracker)}
//	// 每回合开始前（宿主钩子）：
//	turn, err := tracker.Begin()
//	// 需要撤销时：
//	changes, err := tracker.Revert(turn)   // 或交给模型通过 undo 工具调用
//
// # 限制（刻意为之）
//
//   - 只回退文件内容、类型与权限：目录的增删不还原（回退新增文件后可能留下空目录）；
//     扩展属性（xattr/ACL）与文件属主不还原；硬链接关系不重建（内容按路径恢复，
//     同组未回退的路径会被明确 report，见上）。
//   - 不检测"回合外的改动"：快照之后由其它进程写入的文件同样会被当作本回合新增而删除。
//   - 内容上限意味着大文件/二进制文件只能被告知"无法回退"，不会尝试猜测。
//   - Changes/Revert 会读取所有受跟踪文件（每个 ≤ MaxFileBytes）来计算内容哈希与
//     行级差异，代价与 `git status` 同阶；它们只在需要撤销或 dry-run 时调用，不在
//     每回合调用。
//   - 只读磁盘上的文件时同样受进程权限约束；回退失败会返回错误并尽力回滚。
//   - 恢复"未备份内容"的文件（超过 MaxFileBytes / 二进制 / 超出总预算）时，改动检测
//     只能依赖 size+mtime：同一时钟 tick 内"大小不变、mtime 不变"的改写可能漏检。这类
//     文件本来也无法回退内容，漏检只会把"有变更"报成"没变更"，不会写坏盘。
//   - 符号链接的创建走 fsguard 的 SymlinkLiteral（位置过根校验、目标按字面写）+ 根句柄
//     Rename；它是静态接口的一部分，不做运行时能力探测（行为不会因依赖升级悄悄改变）。
//
// 本包只依赖标准库、不调用 git、不联网；所有路径都必须留在工作区根内（拒绝绝对路径、
// ".." 与符号链接逃逸）。
package undo
