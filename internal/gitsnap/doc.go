// Package gitsnap 提供基于 git 的"回合快照"：在不移动 HEAD、不碰用户分支、不改
// 用户暂存区的前提下，记录工作区当前状态，之后可以对比与回退。
//
// # 为什么用 git
//
// 个人 agent 客户端的工作区几乎总是 git 仓库。git 已经提供了内容寻址存储、增量对象、
// 二进制/大文件处理、.gitignore 语义与跨平台路径处理；再写一套"全树快照 + 内容备份 +
// 硬链接/符号链接矩阵"只会得到一份更差、更慢的副本。因此本包只做三件事：
//
//   - Snapshot：把工作区状态拍成一个**隐藏提交**（不移动 HEAD）；
//   - Diff：把隐藏提交与当前工作区对比，给出路径级变更（含增删行数）；
//   - Revert：把工作区恢复成隐藏提交里的样子（含删除快照之后新建的文件）。
//
// # 快照是怎么做的
//
//  1. `git stash create` 生成一个"工作区状态"提交 S（它包含已跟踪文件的增删改，且
//     **不会**改动 HEAD、用户分支或暂存区）；工作区干净时它输出为空，此时用 HEAD
//     代表同样的状态。
//  2. `git ls-files -o --exclude-standard -z` 记录**未跟踪**文件名单（`stash create`
//     不包含未跟踪文件），把这份名单写成一个 blob。
//  3. 用 `git commit-tree` 造一个"元数据提交" A：树里只有 `untracked` 一个条目指向
//     上面的 blob，父提交是 S。快照 ID 就是 A，因此它是**自描述**的——只拿 ID 就能
//     知道"当时哪些文件是未跟踪的"，不依赖进程内状态。
//  4. 把 A 挂到 `refs/rig/undo/<时间戳>-<随机>` 下，避免被 `git gc` 回收；旧引用按
//     数量修剪（默认保留 128 个）。
//
// # 回退语义
//
//   - 已跟踪文件：`git checkout <S> -- <path>` 恢复内容与权限（含符号链接、可执行位）；
//   - 回合里新建的文件（含未跟踪的）：从工作区删除，并从暂存区移除（如果被 add 过）；
//   - `.gitignore` 忽略的文件：**不动**（既不在快照里，也不在"新建"名单里）；
//   - 快照之前就存在的未跟踪文件：内容同样被快照（通过 stash 无法覆盖，但 Diff 用
//     "当时未跟踪名单"把它识别为未跟踪，Revert 会按需恢复/保留）；
//   - 不碰 HEAD、不碰用户分支、不 unstage 用户自己的改动（只处理本回合涉及的路径）。
//
// # 非 git 仓库
//
// 打开时返回 ErrNotGitRepo，调用方应当降级为"不提供 undo"，而不是自己实现文件快照。
//
// # 平台
//
// 所有命令都以 `git -C <dir>` 形式执行，路径处理交给 git，因此 Windows 上同样可用
// （要求 PATH 里有 git 可执行文件）。
