// Package filewatch 用**轮询**方式监听一个工作区目录，产出"文件被创建 / 修改 /
// 删除"的事件。
//
// 它刻意不引入 fsnotify 一类的依赖：只有标准库、纯 Go、跨平台（Linux/macOS/
// Windows 同一套语义），代价是事件有轮询延迟（约 Interval，去抖窗口另加
// Debounce）。
//
// # 典型用途
//
//   - 外部改动检测：模型准备改一个文件前，先确认它没有被别人改过；
//   - 撤销/冲突提示：把同一份基线快照留到写入点上，写入前对比；
//   - 长任务感知工作区已变化。
//
// # 语义
//
//   - Start 时先同步建立**基线**（扫描一次，不产出任何事件）；因此 Start 返回
//     之后对文件系统的改动一定能被观察到。
//   - 之后每个 Interval 扫描一次；两次扫描之间的差异按路径合并，同一路径在
//     Debounce 窗口内的连续变化只产出一条事件，且事件内容是该窗口结束时的
//     状态（净效果：新建后又被删掉的文件不会产出任何事件）。
//   - 只比 (size, mtime)；开启 Digest 时额外用 sha256 比对内容。mtime 精度不足
//     的文件系统上，同 size 的原地改写只有开启 Digest 才能发现。
//   - 符号链接**不跟随**：链接本身作为一个条目出现（大小取 lstat 结果、摘要为空）。
//   - Options.Ignore 命中目录时整棵子树跳过；默认忽略 .git/node_modules/
//     vendor/dist/build。
//   - 条目数触顶 MaxFiles 时只保留字典序靠前的前 N 个，Notice 一次，不报错也
//     不停止。
//
// # 生命周期
//
// Close（或 ctx 取消）之后 Events 通道被关闭，但 **Snapshot 仍然可用**：它返回
// 最后已知的工作区状态，供收尾/诊断（"关停时工作区里有什么"）使用，不会因为
// 通道关闭而失效。Start 是幂等的；Close 之后再 Start 不会复活 watcher。
//
// # 轮询开销
//
// 每个 Interval 扫一次整棵目录（O(条目数)），没有事件循环、没有 busy-wait：1 秒
// 间隔就是 1 秒一次扫描，CPU 占用与目录规模成正比、与时间无关。默认 Interval
// (1s) 适合 ≤1 万文件的工作区；更大或更小的值按需要调整，测试里对"1 秒内的扫描
// 次数"有断言钉住（防止退化成忙等）。
//
// # 边界
//
// 轮询只看得到"扫描时刻的状态"，看不到中间过程；两次扫描之间创建又删除的文件
// 不会产生事件。本包不做内容快照保留（那是调用方的事，见 Changed）。
